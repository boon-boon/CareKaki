// Netlify build helper.
//
// The MCP server reads its provider catalogue from disk at runtime. Serverless
// bundles ship without the repository working tree, so the CSV is embedded into
// a small ES module that netlify/functions/mcp.mjs imports and materialises into
// the function's writable /tmp directory before the first MCP server starts.
//
// Run after `npm run build` (tsc -> dist/), which the `build:netlify` script
// already chains.
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const csvSource = path.join(root, "carekaki_providers_demo.csv");
const outputDir = path.join(root, "netlify");
const outputFile = path.join(outputDir, "providers-data.mjs");

const csv = await readFile(csvSource, "utf8");
if (!csv.trim()) {
  console.error(`build-netlify: ${csvSource} is empty; refusing to embed an empty catalogue.`);
  process.exit(1);
}

const module = [
  "// AUTO-GENERATED by scripts/build-netlify.mjs — do not edit by hand.",
  "// Embedded copy of carekaki_providers_demo.csv for the serverless bundle.",
  `export const PROVIDERS_CSV = ${JSON.stringify(csv)};`,
  "",
].join("\n");

await mkdir(outputDir, { recursive: true });
await writeFile(outputFile, module, "utf8");
console.error(`build-netlify: embedded ${csv.length} bytes of provider CSV -> ${path.relative(root, outputFile)}`);
